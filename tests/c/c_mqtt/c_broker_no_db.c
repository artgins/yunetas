/****************************************************************************
 *          C_BROKER_NO_DB.C
 *
 *          Driver of the test of C_MQTT_BROKER with mqtt_persistent_db
 *          false. The broker keeps its clients, sessions and retained
 *          messages only in its treedb, so it has no mode without one: the
 *          attribute false is refused at start-up, with ONE critical log
 *          that names it, and the broker does not play. Here its
 *          on_critical_error is 0, so the yuno does not exit (the default,
 *          2, ends it with exit 0).
 *
 *          1. After the start, the broker is not playing.
 *          2. Two seconds later (two ticks of its timer, 1 s), nothing more
 *             was logged.
 *
 *          Up to 7.30.26 the broker played without a treedb: every CONNECT
 *          was refused, and its timer logged two ERRORs per tick (the
 *          session expiry and the will delay listing the nodes of a NULL
 *          treedb).
 *
 *          Copyright (c) 2026, ArtGins.
 *          All Rights Reserved.
 ****************************************************************************/
