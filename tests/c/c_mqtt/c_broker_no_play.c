/****************************************************************************
 *          C_BROKER_NO_PLAY.C
 *
 *          Driver of the test of a broker that runs and never plays: its
 *          service is started (the treedb and the queues open in mt_start)
 *          and not played, as with `run-yuno play=0` then `kill-yuno`, or a
 *          standalone broker without yuno.autoplay. Half a second later the
 *          yuno ends, and the broker stops (mt_stop closes its database and
 *          takes the queues back from its input side). No ERROR may be
 *          logged.
 *
 *          Up to 7.30.26 the broker knew its input side only once played:
 *          the stop logged the ERROR "gobj NULL" with a stack, from
 *          gobj_walk_gobj_children_tree() in broadcast_tranger_queues().
 *
 *          Copyright (c) 2026, ArtGins.
 *          All Rights Reserved.
 ****************************************************************************/
