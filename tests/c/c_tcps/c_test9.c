/***********************************************************************
 *          C_TEST9.C
 *
 *          A class to test C_TCP / C_TCP_S
 *          Test: a TLS client whose trusted certificate cannot be loaded
 *          fails its connection, not the yuno
 *
 *          A C_TCP client with `ssl_trusted_certificate` naming a file that
 *          does not exist. Its ytls is built when it connects: the file
 *          cannot be loaded, one ERROR, and the connection is refused. The
 *          yuno goes on. Up to 7.30.3 the OpenSSL backend exited the yuno
 *          there with code 0 (LOG_OPT_EXIT_ZERO, meant for a SERVER that
 *          cannot load its certificate at its first start): an agent whose
 *          controlcenter link named a missing file died, while the mbedTLS
 *          backend only refused the connection.
 *
 *          Tasks
 *          - Start the output side: the client tries to connect
 *          - After 1000 ms (before its next attempt, 2000 ms): the yuno is
 *            alive, the link did not open; end
 *
 *          Copyright (c) 2026, ArtGins.
 *          All Rights Reserved.
 ***********************************************************************/
